package com.entity;

public enum ReservationStatus {
    RESERVED,    // Лимит зарезервирован, операция в процессе
    CONFIRMED,   // Операция успешно завершена, лимит окончательно списан
    CANCELLED,   // Операция отменена до подтверждения, лимит возвращён
    ROLLED_BACK  // Операция была подтверждена, но позже отменена
}